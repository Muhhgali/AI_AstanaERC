export type EpdEarlyPaymentLanguage = "ru" | "kk";

function normalize(text: string) {
  return text.toLowerCase().replace(/ё/g, "е");
}

export function isEpdEarlyPaymentDifferenceIntent(question: string) {
  const normalized = normalize(question);
  const hasReceiptContext = [
    "епд",
    "квитанц",
    "новая квитанц",
    "новый епд",
    "после 11",
    "11 числа",
    "сформир",
    "вышла квитанц",
    "түбіртек",
  ].some((phrase) => normalized.includes(phrase));
  const hasPaymentContext = [
    "оплатил",
    "оплатила",
    "оплата",
    "платеж",
    "платёж",
    "чек",
    "халык",
    "halyk",
    "банк",
    "төлем",
  ].some((phrase) => normalized.includes(phrase));
  const hasDifferenceSignal = [
    "отминус",
    "вычесть",
    "минус",
    "разниц",
    "сколько доплат",
    "только",
    "уже оплат",
    "раньше чем квитанц",
    "до выхода квитанц",
    "до формирования",
  ].some((phrase) => normalized.includes(phrase));

  return hasReceiptContext && hasPaymentContext && hasDifferenceSignal;
}

